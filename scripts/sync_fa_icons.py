JS_HELPERS = r'''
/** @param {string} name
 *  @param {{ brand?: boolean, className?: string }} [opts]
 */
export function faSvg(name, opts = {}) {
  const brand = Boolean(opts.brand);
  const set = brand ? "brands" : "light";
  const entry = FA_ICONS[set]?.[name] || FA_ICONS.light?.[name];
  if (!entry) {
    console.warn("[fa] missing icon", set, name);
    return "";
  }
  const cls = ["fa-icon", opts.className].filter(Boolean).join(" ");
  const paths = entry.paths
    .map((d) => `<path fill="currentColor" d="${d}"></path>`)
    .join("");
  return `<svg class="${cls}" viewBox="${entry.viewBox}" focusable="false" aria-hidden="true">${paths}</svg>`;
}

export function faBrandSvg(name, opts = {}) {
  return faSvg(name, { ...opts, brand: true });
}

/** Create an SVG element for icon buttons. */
export function faSvgElement(name, opts = {}) {
  const wrap = document.createElement("span");
  wrap.innerHTML = faSvg(name, opts);
  return wrap.firstElementChild;
}

/** Hydrate [data-fa] / [data-fa-brands] placeholders. */
export function hydrateFaIcons(root = document) {
  root.querySelectorAll("[data-fa]").forEach((el) => {
    const name = el.getAttribute("data-fa");
    if (!name) return;
    const brand =
      el.hasAttribute("data-fa-brands") || el.getAttribute("data-fa-set") === "brands";
    el.innerHTML = faSvg(name, {
      brand,
      className: el.getAttribute("data-fa-class") || "",
    });
  });
}
'''


def extract(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.search(r'viewBox="([^"]+)"', text)
    view_box = m.group(1) if m else "0 0 512 512"
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', text)
    return {"viewBox": view_box, "paths": paths}


def main() -> None:
    light = [n for n in LIGHT if (FA / "light" / f"{n}.svg").exists()]
    missing = [n for n in LIGHT if n not in light]
    if missing:
        print("skip missing light:", ", ".join(missing))

    data = {"light": {}, "brands": {}}
    for name in light:
        src = FA / "light" / f"{name}.svg"
        data["light"][name] = extract(src)
        dest_dir = OUT_DIR / "light"
        dest_dir.mkdir(parents=True, exist_ok=True)
        (dest_dir / f"{name}.svg").write_text(src.read_text(encoding="utf-8"), encoding="utf-8")

    for name in BRANDS:
        src = FA / "brands" / f"{name}.svg"
        if not src.exists():
            raise SystemExit(f"missing brand icon: {name}")
        data["brands"][name] = extract(src)
        dest_dir = OUT_DIR / "brands"
        dest_dir.mkdir(parents=True, exist_ok=True)
        (dest_dir / f"{name}.svg").write_text(src.read_text(encoding="utf-8"), encoding="utf-8")

    header = (
        "/** Font Awesome Pro 6.5.2 icons (light + brands). "
        "Generated by scripts/sync_fa_icons.py — do not edit by hand. */\n"
        f"export const FA_ICONS = {json.dumps(data, indent=2)};\n"
    )
    OUT_JS.write_text(header + JS_HELPERS, encoding="utf-8")
    print(
        f"wrote {OUT_JS.relative_to(ROOT)} "
        f"({len(data['light'])} light, {len(data['brands'])} brands)"
    )


if __name__ == "__main__":
    main()
